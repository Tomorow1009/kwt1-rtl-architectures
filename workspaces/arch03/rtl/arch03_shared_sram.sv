`timescale 1ns/1ps
// NEW team platform extension, not an original platform address assignment.
// 512 KiB: 32 banks * 4096 words * 32 bits. 64 physical 4096x16 macros.
module arch03_shared_sram #(parameter [31:0] BASE_ADDR=32'ha0000000)(
    input wire clk,rst_n,
    input wire cmd_valid,output wire cmd_ready,
    input wire [31:0] cmd_addr,input wire cmd_read,
    input wire [31:0] cmd_wdata,input wire [3:0] cmd_wmask,
    output reg rsp_valid,input wire rsp_ready,
    output reg [31:0] rsp_rdata,output reg rsp_err
);
    reg read_pending;
    reg [4:0] bank_q;
    wire fire=cmd_valid && cmd_ready;
    // ICB byte/halfword stores carry byte address and lane mask, as generated by E203 LSU.
    // Reads return the aligned word; LSU extracts the addressed byte/halfword.
    wire mapped=(cmd_addr[31:19]==BASE_ADDR[31:19]);
    wire [31:0] bank_data[0:31];
    assign cmd_ready=rst_n && !rsp_valid && !read_pending;
    genvar g;
    generate for(g=0;g<32;g=g+1) begin:banks
        wire selected=fire && mapped && cmd_addr[18:14]==g;
        arch03_sram_half low(.clk(clk),.cs(selected),.we(!cmd_read),
            .addr(cmd_addr[13:2]),.wdata(cmd_wdata[15:0]),.mask(cmd_wmask[1:0]),.rdata(bank_data[g][15:0]));
        arch03_sram_half high(.clk(clk),.cs(selected),.we(!cmd_read),
            .addr(cmd_addr[13:2]),.wdata(cmd_wdata[31:16]),.mask(cmd_wmask[3:2]),.rdata(bank_data[g][31:16]));
    end endgenerate
    always @(posedge clk or negedge rst_n) begin
        if(!rst_n) begin read_pending<=0;bank_q<=0;rsp_valid<=0;rsp_rdata<=0;rsp_err<=0;end
        else begin
            if(rsp_valid && rsp_ready) rsp_valid<=0;
            if(read_pending) begin
                rsp_rdata<=bank_data[bank_q];rsp_err<=0;rsp_valid<=1;read_pending<=0;
            end
            if(fire) begin
                if(!mapped || !cmd_read) begin
                    rsp_valid<=1;rsp_rdata<=0;rsp_err<=!mapped;
                end else begin bank_q<=cmd_addr[18:14];read_pending<=1;end
            end
        end
    end
endmodule

`ifndef ARCH02_BEHAVIORAL
`include "arch02_sram_config.vh"
`endif
module arch03_sram_half(
    input wire clk,cs,we,input wire [11:0] addr,
    input wire [15:0] wdata,input wire [1:0] mask,output wire [15:0] rdata
);
`ifdef ARCH02_BEHAVIORAL
    reg [15:0] mem[0:4095];
    reg [15:0] q;
    assign rdata=q;
    always @(posedge clk) if(cs) begin
        if(we) begin
            if(mask[0]) mem[addr][7:0]<=wdata[7:0];
            if(mask[1]) mem[addr][15:8]<=wdata[15:8];
        end else q<=mem[addr];
    end
`else
    wire wenable=cs && we;
    wire [15:0] enables={{8{wenable && mask[1]}},{8{wenable && mask[0]}}};
    RAMSP4096X16 memory(.Q(rdata),.CLK(clk),
        .CEN(`A02_4096_CEN_LOW ? !cs : cs),
        .GWEN(`A02_4096_GWEN_LOW ? !wenable : wenable),
        .WEN(`A02_4096_WEN_LOW ? ~enables : enables),
        .A(addr),.D(wdata),.EMA(`A02_4096_EMA),.EMAW(`A02_4096_EMAW),.RET1N(`A02_4096_RET1N));
`endif
endmodule
